/* Times-style bitmaps. Bit 7 of each byte is the leftmost pixel.
 * Glyph order: ASCII 32-127. Index is the character code minus 32.
 */

int8_t getCharIndex(uint8_t c) {
  if (c < ' ' || c > 127)
    return -1;
  return c - ' ';
}

