/* 1px stroke bitmaps. Bit 7 of each byte is the leftmost pixel.
 * Glyph order: 0-9, A-Z, a-z.
 */

int8_t getCharIndex(uint8_t c) {
  if (c >= '0' && c <= '9')
    return (c - 48);
  else if (c >= 'A' && c <= 'Z')
    return (c - 'A' + 10);
  else if (c >= 'a' && c <= 'z')
    return (c - 'a' + 36);
  return -1;
};

